      function socRenderGrid(activeIdx){
        let h = '';
        for(let i=0;i<12;i++){
          const has = i < FOL_DATA.length;
          const cls = 'soc-month-cell' + (i===activeIdx?' soc-active':'') + (!has?' soc-disabled':'');
          const click = has ? ` onclick="socSelectMonth(${i})"` : '';
          h += `<div class="${cls}"${click}>${SOC_MONTH_ABBR[i]}</div>`;
        }
        document.getElementById('socGrid').innerHTML = h;
      }
